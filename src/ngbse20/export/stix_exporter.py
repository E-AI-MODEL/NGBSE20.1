"""
STIX exporter for NGBSE 20.3.
Exports findings and data to STIX 2.1 format.
"""

from pathlib import Path
from typing import Any, Dict, List
from datetime import datetime

from .base import Exporter, ExportError, DataValidationError


class STIXExporter(Exporter):
    """Exports data to STIX 2.1 format."""
    
    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.stix_version = config.get("stix_version", "2.1")
        self.include_indicators = config.get("include_indicators", True)
        self.include_observables = config.get("include_observables", True)
        self.include_relationships = config.get("include_relationships", True)
    
    def export(self, data: Dict[str, Any], output_path: Path) -> bool:
        """Export data to STIX format."""
        try:
            if not self.validate_data(data):
                raise DataValidationError("Data validation failed")
            
            # Ensure output directory exists
            output_path.parent.mkdir(parents=True, exist_ok=True)
            
            # Import stix2 here to avoid dependency issues
            try:
                import stix2
            except ImportError:
                self.logger.error("stix2 not installed. Install with: pip install stix2")
                return False
            
            # Generate STIX objects
            stix_objects = self._generate_stix_objects(data)
            
            # Create STIX bundle
            bundle = stix2.Bundle(stix_objects, allow_custom=True)
            
            # Write STIX file
            with open(output_path, 'w', encoding='utf-8') as f:
                f.write(bundle.serialize(pretty=True))
            
            self.logger.info(f"STIX export completed: {output_path}")
            return True
            
        except Exception as e:
            self.logger.error(f"STIX export failed: {e}")
            raise ExportError(f"STIX export failed: {e}")
    
    def get_file_extension(self) -> str:
        """Get STIX file extension."""
        return ".json"
    
    def get_mime_type(self) -> str:
        """Get STIX MIME type."""
        return "application/json"
    
    def validate_data(self, data: Dict[str, Any]) -> bool:
        """Validate data for STIX export."""
        if not isinstance(data, dict):
            return False
        
        findings = data.get("findings", [])
        if not isinstance(findings, list):
            return False
        
        return True  # STIX can handle any data structure
    
    def _generate_stix_objects(self, data: Dict[str, Any]) -> List[Any]:
        """Generate STIX objects from data."""
        try:
            import stix2
        except ImportError:
            return []
        
        stix_objects = []
        findings = data.get("findings", [])
        config_info = data.get("config", {})
        
        # Create identity for NGBSE
        identity = stix2.Identity(
            name="NGBSE 20.3",
            identity_class="system",
            description="Next Generation Business Security Engine",
            custom_properties={
                "x_ngbse_version": "20.3",
                "x_ngbse_type": "security_analysis_engine"
            }
        )
        stix_objects.append(identity)
        
        # Create report
        report = stix2.Report(
            name="NGBSE Security Analysis Report",
            description="Security analysis report generated by NGBSE 20.3",
            report_types=["threat-assessment"],
            published=datetime.now(),
            created_by_ref=identity.id,
            object_refs=[],
            custom_properties={
                "x_ngbse_target": config_info.get("target", "Unknown"),
                "x_ngbse_findings_count": len(findings)
            }
        )
        stix_objects.append(report)
        
        # Process findings
        for finding in findings:
            finding_objects = self._create_finding_objects(finding, identity, report)
            stix_objects.extend(finding_objects)
        
        return stix_objects
    
    def _create_finding_objects(self, finding: Dict[str, Any], identity: Any, report: Any) -> List[Any]:
        """Create STIX objects for a single finding."""
        try:
            import stix2
        except ImportError:
            return []
        
        objects = []
        finding_id = finding.get("id", "")
        finding_type = finding.get("type", "unknown")
        severity = finding.get("severity", "unknown")
        description = finding.get("description", "")
        source = finding.get("source", "")
        timestamp = finding.get("timestamp", "")
        
        # Create indicator if applicable
        if self.include_indicators and finding_type in ["ip", "domain", "url", "hash"]:
            indicator = stix2.Indicator(
                name=f"NGBSE Finding: {finding_type}",
                description=description,
                indicator_types=["malicious-activity"],
                pattern=f"[{finding_type}:value = '{finding.get('value', '')}']",
                pattern_type="stix",
                valid_from=datetime.now(),
                created_by_ref=identity.id,
                custom_properties={
                    "x_ngbse_finding_id": finding_id,
                    "x_ngbse_severity": severity,
                    "x_ngbse_source": source
                }
            )
            objects.append(indicator)
        
        # Create observable if applicable
        if self.include_observables and finding_type in ["ip", "domain", "url", "hash"]:
            observable_type = self._map_finding_type_to_observable(finding_type)
            if observable_type:
                observable = stix2.Observable(
                    type=observable_type,
                    value=finding.get("value", ""),
                    custom_properties={
                        "x_ngbse_finding_id": finding_id,
                        "x_ngbse_severity": severity,
                        "x_ngbse_source": source
                    }
                )
                objects.append(observable)
        
        # Create vulnerability if applicable
        if finding_type in ["vulnerability", "cve", "cwe"]:
            vulnerability = stix2.Vulnerability(
                name=f"NGBSE Finding: {finding_type}",
                description=description,
                created_by_ref=identity.id,
                custom_properties={
                    "x_ngbse_finding_id": finding_id,
                    "x_ngbse_severity": severity,
                    "x_ngbse_source": source
                }
            )
            objects.append(vulnerability)
        
        # Create threat actor if applicable
        if finding_type in ["threat_actor", "actor", "group"]:
            threat_actor = stix2.ThreatActor(
                name=f"NGBSE Finding: {finding_type}",
                description=description,
                threat_actor_types=["unknown"],
                created_by_ref=identity.id,
                custom_properties={
                    "x_ngbse_finding_id": finding_id,
                    "x_ngbse_severity": severity,
                    "x_ngbse_source": source
                }
            )
            objects.append(threat_actor)
        
        # Create relationship to report
        for obj in objects:
            relationship = stix2.Relationship(
                relationship_type="related-to",
                source_ref=obj.id,
                target_ref=report.id,
                created_by_ref=identity.id
            )
            objects.append(relationship)
        
        return objects
    
    def _map_finding_type_to_observable(self, finding_type: str) -> str:
        """Map finding type to STIX observable type."""
        mapping = {
            "ip": "ipv4-addr",
            "domain": "domain-name",
            "url": "url",
            "hash": "file",
            "email": "email-addr",
            "file": "file"
        }
        return mapping.get(finding_type, "")
    
    def export_indicators_only(self, data: Dict[str, Any], output_path: Path) -> bool:
        """Export only indicators to STIX format."""
        try:
            import stix2
        except ImportError:
            self.logger.error("stix2 not installed. Install with: pip install stix2")
            return False
        
        findings = data.get("findings", [])
        if not findings:
            return False
        
        # Create identity
        identity = stix2.Identity(
            name="NGBSE 20.3",
            identity_class="system",
            description="Next Generation Business Security Engine"
        )
        
        # Create indicators only
        indicators = []
        for finding in findings:
            if finding.get("type") in ["ip", "domain", "url", "hash"]:
                indicator = stix2.Indicator(
                    name=f"NGBSE Finding: {finding.get('type', 'unknown')}",
                    description=finding.get("description", ""),
                    indicator_types=["malicious-activity"],
                    pattern=f"[{finding.get('type', 'unknown')}:value = '{finding.get('value', '')}']",
                    pattern_type="stix",
                    valid_from=datetime.now(),
                    created_by_ref=identity.id
                )
                indicators.append(indicator)
        
        if not indicators:
            return False
        
        # Create bundle with indicators
        bundle = stix2.Bundle([identity] + indicators, allow_custom=True)
        
        # Write STIX file
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(bundle.serialize(pretty=True))
        
        return True