"""
HTML exporter for NGBSE 20.3.
Exports findings and data to HTML format with templates.
"""

from pathlib import Path
from typing import Any, Dict, List
from datetime import datetime
import json

from .base import Exporter, ExportError, DataValidationError


class HTMLExporter(Exporter):
    """Exports data to HTML format with templates."""

    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.template_path = config.get("html_template_path")
        self.include_charts = config.get("include_charts", True)
        self.include_tables = config.get("include_tables", True)
        self.theme = config.get("html_theme", "default")
        self.title = config.get("html_title", "NGBSE 20.3 Security Analysis Report")

    def export(self, data: Dict[str, Any], output_path: Path) -> bool:
        """Export data to HTML format."""
        try:
            if not self.validate_data(data):
                raise DataValidationError("Data validation failed")

            # Ensure output directory exists
            output_path.parent.mkdir(parents=True, exist_ok=True)

            # Generate HTML content
            html_content = self._generate_html(data)

            # Write HTML file
            with open(output_path, "w", encoding="utf-8") as f:
                f.write(html_content)

            self.logger.info(f"HTML export completed: {output_path}")
            return True

        except Exception as e:
            self.logger.error(f"HTML export failed: {e}")
            raise ExportError(f"HTML export failed: {e}")

    def get_file_extension(self) -> str:
        """Get HTML file extension."""
        return ".html"

    def get_mime_type(self) -> str:
        """Get HTML MIME type."""
        return "text/html"

    def validate_data(self, data: Dict[str, Any]) -> bool:
        """Validate data for HTML export."""
        if not isinstance(data, dict):
            return False

        findings = data.get("findings", [])
        if not isinstance(findings, list):
            return False

        return True  # HTML can handle any data structure

    def _generate_html(self, data: Dict[str, Any]) -> str:
        """Generate HTML content from data."""
        findings = data.get("findings", [])
        config_info = data.get("config", {})

        # Generate HTML
        html = f"""
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{self.title}</title>
    <style>
        {self._get_css_styles()}
    </style>
</head>
<body>
    <div class="container">
        <header>
            <h1>{self.title}</h1>
            <div class="metadata">
                <p>Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
                <p>Total Findings: {len(findings)}</p>
                <p>Target: {config_info.get('target', 'Unknown')}</p>
            </div>
        </header>
        
        <main>
            {self._generate_summary_section(findings)}
            {self._generate_findings_section(findings)}
            {self._generate_recommendations_section(findings)}
        </main>
        
        <footer>
            <p>Generated by NGBSE 20.3 - Next Generation Business Security Engine</p>
        </footer>
    </div>
    
    <script>
        {self._get_javascript()}
    </script>
</body>
</html>
        """

        return html

